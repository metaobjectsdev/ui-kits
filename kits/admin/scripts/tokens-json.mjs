// Writes packages/admin-tokens/tokens.json from tokens.css, the single source of truth.
// The JSON follows the W3C Design Tokens Community Group (DTCG) format, so a renderer that is
// not CSS (a native app, a PDF writer, Style Dictionary) can read the tokens without parsing CSS.
// `--check` fails instead of writing when the committed JSON is out of date.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const dir = fileURLToPath(new URL('../packages/admin-tokens/', import.meta.url));
const css = readFileSync(`${dir}tokens.css`, 'utf8');

/** The custom properties declared in the first block that opens with `selector {`. */
function block(selector) {
  const start = css.indexOf(`${selector} {`);
  if (start < 0) throw new Error(`tokens.css: no block for ${selector}`);
  const body = css.slice(css.indexOf('{', start) + 1, css.indexOf('}', start));
  const props = {};
  for (const [, name, value] of body.matchAll(/--([\w-]+):\s*([^;]+);/g)) props[name] = value.trim();
  return props;
}

/** Splits on commas that are not inside parentheses. */
function splitTopLevel(text) {
  const parts = [];
  let depth = 0;
  let current = '';
  for (const char of text) {
    if (char === '(') depth++;
    if (char === ')') depth--;
    if (char === ',' && depth === 0) {
      parts.push(current.trim());
      current = '';
    } else {
      current += char;
    }
  }
  parts.push(current.trim());
  return parts;
}

const hex2 = (n) => Math.round(n).toString(16).padStart(2, '0');

/** `#rgb`, `#rrggbb` or `rgba(r, g, b, a)` as a DTCG hex colour; `lossy` when the alpha was rounded. */
function color(value) {
  if (/^#[0-9a-f]{6}$/i.test(value)) return { value: value.toLowerCase() };
  const rgba = value.match(/^rgba?\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*(?:,\s*([\d.]+)\s*)?\)$/);
  if (!rgba) throw new Error(`tokens.css: cannot read colour ${value}`);
  const alpha = rgba[4] === undefined ? 1 : Number(rgba[4]);
  const hex = `#${hex2(rgba[1])}${hex2(rgba[2])}${hex2(rgba[3])}${alpha === 1 ? '' : hex2(alpha * 255)}`;
  return { value: hex, css: value };
}

const px = (text) => {
  if (text === '0') return '0px';
  if (!/^-?[\d.]+px$/.test(text)) throw new Error(`tokens.css: expected a px length, got ${text}`);
  return text;
};

/** `0 1px 2px rgba(...), 0 1px 3px rgba(...)` as DTCG shadow layers; `none` is one clear layer. */
function shadow(value) {
  if (value === 'none') {
    return { value: [{ color: '#00000000', offsetX: '0px', offsetY: '0px', blur: '0px', spread: '0px' }], css: 'none' };
  }
  const layers = splitTopLevel(value).map((layer) => {
    const match = layer.match(/^(\S+)\s+(\S+)\s+(\S+)(?:\s+(\S+))?\s+(rgba?\([^)]*\)|#[0-9a-f]+)$/i);
    if (!match) throw new Error(`tokens.css: cannot read shadow ${layer}`);
    return { color: color(match[5]).value, offsetX: px(match[1]), offsetY: px(match[2]), blur: px(match[3]), spread: px(match[4] ?? '0') };
  });
  return { value: layers, css: value };
}

/** One DTCG token for a custom property. `group` is the top-level group the token lives in. */
function token(name, value) {
  const alias = value.match(/^var\(--([\w-]+)\)$/);
  let type;
  let out;
  if (name.startsWith('font-')) {
    type = 'fontFamily';
    out = alias
      ? { value: `{base.${alias[1]}}` }
      : { value: splitTopLevel(value).map((family) => family.replace(/^["']|["']$/g, '')) };
  } else if (name.startsWith('shadow-')) {
    type = 'shadow';
    out = shadow(value);
  } else if (/^(#|rgba?\()/.test(value)) {
    type = 'color';
    out = color(value);
  } else {
    type = 'dimension';
    out = { value: px(value) };
  }
  const result = { $value: out.value, $type: type };
  // The CSS stays authoritative: keep the exact text where the DTCG form is not the same bytes.
  if (out.css) result.$extensions = { 'dev.metaobjects.admin-kit': { css: out.css } };
  return result;
}

const group = (props) => Object.fromEntries(Object.entries(props).map(([name, value]) => [name, token(name, value)]));

const tokens = {
  $description:
    'W3C Design Tokens (DTCG) copy of tokens.css, generated by scripts/tokens-json.mjs; do not edit. ' +
    'Token names are the CSS custom property names without the leading --. ' +
    '"base" holds the theme-independent tokens; "light" and "dark" hold the same colour tokens per theme; ' +
    '"coarsePointer" holds the overrides for touch screens (@media (pointer: coarse)). ' +
    'A token with $extensions["dev.metaobjects.admin-kit"].css keeps the exact CSS text where the DTCG value is an equivalent form.',
  base: group(block(':root')),
  light: group(block(':root,\n[data-theme="light"]')),
  dark: group(block('[data-theme="dark"]')),
  coarsePointer: group(block('@media (pointer: coarse) {\n  :root')),
};

const json = `${JSON.stringify(tokens, null, 2)}\n`;
const target = `${dir}tokens.json`;

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(target, 'utf8');
  } catch {
    // missing counts as stale
  }
  if (current !== json) {
    console.error('tokens.json is out of date with tokens.css: run `pnpm tokens:json`.');
    process.exit(1);
  }
  console.log('tokens.json is up to date.');
} else {
  // Unchanged bytes are not rewritten.
  let current = '';
  try {
    current = readFileSync(target, 'utf8');
  } catch {
    // first write
  }
  if (current !== json) writeFileSync(target, json);
  const count = (g) => Object.keys(g).length;
  console.log(`wrote ${count(tokens.base)} base, ${count(tokens.light)} light, ${count(tokens.dark)} dark tokens`);
}
