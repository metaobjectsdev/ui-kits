// Writes packages/admin-css/admin.css: the tokens and the components in one self-contained
// stylesheet, for a page or renderer that links CSS directly and has no bundler to resolve an
// @import. It is tokens.css followed by components.css, nothing else, so the two never drift.
// `--check` fails instead of writing when the committed file is out of date.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const packages = fileURLToPath(new URL('../packages/', import.meta.url));
const tokens = readFileSync(`${packages}admin-tokens/tokens.css`, 'utf8');
const components = readFileSync(`${packages}admin-css/components.css`, 'utf8');

const css = `/* =====================================================================================
 * @metaobjectsdev/admin-css/admin.css: the admin kit in one file, no bundler needed.
 *
 * Generated by scripts/build-admin-css.mjs; do not edit. It is
 * @metaobjectsdev/admin-tokens/tokens.css followed by components.css. Link this one file, or
 * import the two separately; do not load both forms on one page.
 * ===================================================================================== */

${tokens.trimEnd()}

${components.trimEnd()}
`;

const target = `${packages}admin-css/admin.css`;
let current = '';
try {
  current = readFileSync(target, 'utf8');
} catch {
  // missing counts as stale
}

if (process.argv.includes('--check')) {
  if (current !== css) {
    console.error('admin.css is out of date with tokens.css and components.css: run `pnpm admin-css:build`.');
    process.exit(1);
  }
  console.log('admin.css is up to date.');
} else {
  if (current !== css) writeFileSync(target, css);
  console.log('wrote packages/admin-css/admin.css');
}
